#!/bin/sh
# Extract the btrfs userspace headers required by compsize.
#
# Placement mirrors btrfs-progs' own `make install`: the libbtrfs_headers set is copied flat into
# <includedir>/btrfs/, i.e. the source file kernel-shared/ctree.h becomes <includedir>/btrfs/ctree.h.
# Output: $DEST/btrfs/{ioctl.h,ctree.h,kerncompat.h,...}
set -eu

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
LOCK="$ROOT/upstream.lock"

_lock() { sed -n "s/^$1[[:space:]]*=[[:space:]]*//p" "$LOCK" | tr -d '\r' | head -1; }
TAG=$(_lock 'btrfsprogs\.tag')
REPO=$(_lock 'btrfsprogs\.repo')

DEST="${DEST:-$ROOT/hdr}"
WORK="${WORK:-$ROOT/build/work}"
SRCDIR="$WORK/btrfs-progs"

# btrfs-progs v5.11 libbtrfs_headers (exactly the set `make install` ships)
HEADERS="common/send-stream.h common/send-utils.h send.h kernel-lib/rbtree.h btrfs-list.h
crypto/crc32c.h kernel-lib/list.h kerncompat.h kernel-lib/radix-tree.h kernel-lib/sizes.h
kernel-lib/raid56.h common/extent-cache.h kernel-shared/extent_io.h ioctl.h
kernel-shared/ctree.h btrfsck.h"

if [ ! -d "$SRCDIR" ]; then
  echo ">> clone $REPO @ $TAG"
  mkdir -p "$WORK"
  git clone --depth 1 --branch "$TAG" "$REPO" "$SRCDIR"
fi

mkdir -p "$DEST/btrfs"
for h in $HEADERS; do
  cp "$SRCDIR/$h" "$DEST/btrfs/$(basename "$h")"
done

# version.h is generated by the btrfs-progs build; synthesize the equivalent from version.h.in
sed -e 's/@LIBBTRFS_MAJOR@/5/' -e 's/@LIBBTRFS_MINOR@/11/' \
    -e 's/@LIBBTRFS_PATCHLEVEL@/0/' -e 's/@PACKAGE_VERSION@/5.11/' \
    "$SRCDIR/version.h.in" > "$DEST/btrfs/version.h"

echo ">> headers -> $DEST/btrfs"
ls -1 "$DEST/btrfs" | sed 's/^/   /'
